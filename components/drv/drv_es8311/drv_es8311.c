static esp_err_t es8311_write_reg(uint8_t reg, uint8_t val)
{
    uint8_t buf[2] = { reg, val };
    return i2c_master_transmit(s_dev, buf, sizeof(buf), -1);
}

static esp_err_t es8311_read_reg(uint8_t reg, uint8_t *out_val)
{
    return i2c_master_transmit_receive(s_dev, &reg, 1, out_val, 1, -1);
}

static const struct es8311_coeff_div *es8311_find_coeff(uint32_t mclk, uint32_t rate)
{
    for (size_t i = 0; i < sizeof(s_coeff_div) / sizeof(s_coeff_div[0]); i++) {
        if (s_coeff_div[i].mclk == mclk && s_coeff_div[i].rate == rate) {
            return &s_coeff_div[i];
        }
    }
    return NULL;
}

static esp_err_t es8311_configure_clock_dividers(uint32_t mclk_hz, uint32_t sample_rate_hz)
{
    const struct es8311_coeff_div *c = es8311_find_coeff(mclk_hz, sample_rate_hz);
    if (c == NULL) {
        ESP_LOGE(TAG, "no clock divider entry for mclk=%" PRIu32 " rate=%" PRIu32, mclk_hz, sample_rate_hz);
        return ESP_ERR_INVALID_ARG;
    }

    uint8_t reg;
    esp_err_t err = es8311_read_reg(ES8311_CLK_MANAGER_REG02, &reg);
    if (err != ESP_OK) {
        return err;
    }
    reg = (reg & 0x07) | ((c->pre_div - 1) << 5) | (c->pre_multi << 3);
    err = es8311_write_reg(ES8311_CLK_MANAGER_REG02, reg);
    if (err != ESP_OK) {
        return err;
    }

    err = es8311_write_reg(ES8311_CLK_MANAGER_REG03, (c->fs_mode << 6) | c->adc_osr);
    if (err != ESP_OK) {
        return err;
    }

    err = es8311_write_reg(ES8311_CLK_MANAGER_REG04, c->dac_osr);
    if (err != ESP_OK) {
        return err;
    }

    err = es8311_write_reg(ES8311_CLK_MANAGER_REG05, ((c->adc_div - 1) << 4) | (c->dac_div - 1));
    if (err != ESP_OK) {
        return err;
    }

    err = es8311_read_reg(ES8311_CLK_MANAGER_REG06, &reg);
    if (err != ESP_OK) {
        return err;
    }
    reg = (reg & 0xE0) | ((c->bclk_div < 19) ? (c->bclk_div - 1) : c->bclk_div);
    err = es8311_write_reg(ES8311_CLK_MANAGER_REG06, reg);
    if (err != ESP_OK) {
        return err;
    }

    err = es8311_read_reg(ES8311_CLK_MANAGER_REG07, &reg);
    if (err != ESP_OK) {
        return err;
    }
    reg = (reg & 0xC0) | c->lrck_h;
    err = es8311_write_reg(ES8311_CLK_MANAGER_REG07, reg);
    if (err != ESP_OK) {
        return err;
    }

    return es8311_write_reg(ES8311_CLK_MANAGER_REG08, c->lrck_l);
}

esp_err_t drv_es8311_init(uint32_t sample_rate_hz)
{
    if (s_initialized) {
        return ESP_OK;
    }

    i2c_device_config_t dev_cfg = {
        .dev_addr_length = I2C_ADDR_BIT_LEN_7,
        .device_address = CONFIG_DRV_ES8311_I2C_ADDR,
        .scl_speed_hz = CONFIG_DRV_ES8311_I2C_SPEED_HZ,
    };
    esp_err_t err = bsp_i2c_add_device(&dev_cfg, &s_dev);
    if (err != ESP_OK) {
        ESP_LOGE(TAG, "bsp_i2c_add_device failed: %s", esp_err_to_name(err));
        return err;
    }

    // Reset then power the chip on.
    err = es8311_write_reg(ES8311_RESET_REG00, 0x1F);
    if (err != ESP_OK) {
        return err;
    }
    vTaskDelay(pdMS_TO_TICKS(20));
    err = es8311_write_reg(ES8311_RESET_REG00, 0x00);
    if (err != ESP_OK) {
        return err;
    }
    err = es8311_write_reg(ES8311_RESET_REG00, 0x80);
    if (err != ESP_OK) {
        return err;
    }

    // Clock source: BCLK pin (no MCLK wired), not inverted.
    err = es8311_write_reg(ES8311_CLK_MANAGER_REG01, 0x3F | (1u << 7));
    if (err != ESP_OK) {
        return err;
    }
    uint8_t reg06;
    err = es8311_read_reg(ES8311_CLK_MANAGER_REG06, &reg06);
    if (err != ESP_OK) {
        return err;
    }
    err = es8311_write_reg(ES8311_CLK_MANAGER_REG06, reg06 & ~(1u << 5));
    if (err != ESP_OK) {
        return err;
    }

    uint32_t mclk_hz = sample_rate_hz * ES8311_RES_BITS * 2;
    err = es8311_configure_clock_dividers(mclk_hz, sample_rate_hz);
    if (err != ESP_OK) {
        return err;
    }

    // Slave mode, I2S format, 16-bit in/out (matches bsp_i2s).
    uint8_t reg00;
    err = es8311_read_reg(ES8311_RESET_REG00, &reg00);
    if (err != ESP_OK) {
        return err;
    }
    err = es8311_write_reg(ES8311_RESET_REG00, reg00 & 0xBF);
    if (err != ESP_OK) {
        return err;
    }
    err = es8311_write_reg(ES8311_SDPIN_REG09, 3u << 2);
    if (err != ESP_OK) {
        return err;
    }
    err = es8311_write_reg(ES8311_SDPOUT_REG0A, 3u << 2);
    if (err != ESP_OK) {
        return err;
    }

    // Power up analog circuitry, PGA, ADC modulator, DAC and HP drive.
    err = es8311_write_reg(ES8311_SYSTEM_REG0D, 0x01);
    if (err != ESP_OK) {
        return err;
    }
    err = es8311_write_reg(ES8311_SYSTEM_REG0E, 0x02);
    if (err != ESP_OK) {
        return err;
    }
    err = es8311_write_reg(ES8311_SYSTEM_REG12, 0x00);
    if (err != ESP_OK) {
        return err;
    }
    err = es8311_write_reg(ES8311_SYSTEM_REG13, 0x10);
    if (err != ESP_OK) {
        return err;
    }
    err = es8311_write_reg(ES8311_ADC_REG1C, 0x6A);
    if (err != ESP_OK) {
        return err;
    }
    err = es8311_write_reg(ES8311_DAC_REG37, 0x08);
    if (err != ESP_OK) {
        return err;
    }

    // Analog mic in, max PGA gain.
    err = es8311_write_reg(ES8311_ADC_REG17, 0xC8);
    if (err != ESP_OK) {
        return err;
    }
    err = es8311_write_reg(ES8311_SYSTEM_REG14, 0x1A);
    if (err != ESP_OK) {
        return err;
    }

    s_initialized = true;
    ESP_LOGI(TAG, "init done (addr=0x%02x rate=%" PRIu32 "Hz mclk=%" PRIu32 "Hz, BCLK-derived)",
             CONFIG_DRV_ES8311_I2C_ADDR, sample_rate_hz, mclk_hz);
    return ESP_OK;
}

esp_err_t drv_es8311_set_volume(uint8_t volume_pct)
{
    if (!s_initialized) {
        return ESP_ERR_INVALID_STATE;
    }
    if (volume_pct > 100) {
        volume_pct = 100;
    }
    uint8_t reg32 = (volume_pct == 0) ? 0 : (((uint32_t)volume_pct * 256 / 100) - 1);
    return es8311_write_reg(ES8311_DAC_REG32, reg32);
}

esp_err_t drv_es8311_set_mute(bool mute)
{
    if (!s_initialized) {
        return ESP_ERR_INVALID_STATE;
    }
    uint8_t reg31;
    esp_err_t err = es8311_read_reg(ES8311_DAC_REG31, &reg31);
    if (err != ESP_OK) {
        return err;
    }
    if (mute) {
        reg31 |= (1u << 6) | (1u << 5);
    } else {
        reg31 &= ~((1u << 6) | (1u << 5));
    }
    return es8311_write_reg(ES8311_DAC_REG31, reg31);
}

esp_err_t drv_es8311_set_mic_gain(drv_es8311_mic_gain_t gain)
{
    if (!s_initialized) {
        return ESP_ERR_INVALID_STATE;
    }
    return es8311_write_reg(ES8311_ADC_REG16, (uint8_t)gain);
}
